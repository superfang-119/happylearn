"""Rebuild the self-contained American-English word recordings (Python, Node and FFmpeg with Flite)."""
import array
import base64
import concurrent.futures
import ctypes
import ctypes.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import wave

DIST = Path(__file__).resolve().parents[1] / "dist"
RATE = 16000
# In isolation the voice selects past-tense "read" and adjectival "close".
# Their homophones give the present-tense verb and the verb "shut" used in these lessons.
SPOKEN = {"read": "reed", "close": "cloze"}


def encode(word):
    text = SPOKEN.get(word, word)
    if not text.isalpha() or not text.isascii():
        raise ValueError(f"Expected a single alphabetic word, got {text!r}")
    ffmpeg = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-threads", "1"]
    raw = subprocess.check_output(ffmpeg + [
        "-f", "lavfi", "-i", f"flite=text={text}:voice=slt", "-ar", str(RATE),
        "-ac", "1", "-f", "s16le", "-"
    ])
    return word, compress(raw)


def compress(raw):
    ffmpeg = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-threads", "1"]
    samples = array.array("h", raw)
    if sys.byteorder != "little":
        samples.byteswap()
    first = next(i for i, v in enumerate(samples) if abs(v) > 50)
    last = len(samples) - next(i for i, v in enumerate(reversed(samples)) if abs(v) > 50)
    samples = samples[max(0, first-RATE//15): min(len(samples), last+RATE//10)]
    gain = min(2.5, 27500 / max(abs(v) for v in samples))
    leveled = array.array("h", (round(v * gain) for v in samples))
    if sys.byteorder != "little":
        leveled.byteswap()
    audio = subprocess.run(ffmpeg + [
        "-f", "s16le", "-ar", str(RATE), "-ac", "1", "-i", "-",
        "-map_metadata", "-1", "-codec:a", "libmp3lame", "-b:a", "40k",
        "-write_xing", "0", "-id3v2_version", "0", "-f", "mp3", "-"
    ], input=leveled.tobytes(), check=True, stdout=subprocess.PIPE).stdout
    return base64.b64encode(audio).decode("ascii")


def write_vowels():
    # Request phonemes directly. A word or a spoken letter name is not a reference vowel.
    load = lambda name: ctypes.CDLL(ctypes.util.find_library(name), mode=ctypes.RTLD_GLOBAL)
    flite = load("flite")
    load("flite_usenglish")
    load("flite_cmulex")
    voice_lib = load("flite_cmu_us_slt")
    flite.flite_init()
    voice_lib.register_cmu_us_slt.argtypes = [ctypes.c_char_p]
    voice_lib.register_cmu_us_slt.restype = ctypes.c_void_p
    voice = voice_lib.register_cmu_us_slt(b".")
    synth = flite.flite_phones_to_speech
    synth.argtypes = [ctypes.c_char_p, ctypes.c_void_p, ctypes.c_char_p]
    synth.restype = ctypes.c_float
    vowels = {}
    with tempfile.TemporaryDirectory() as folder:
        for symbol, phone in (("æ", "ae"), ("ɛ", "eh"), ("ɪ", "ih"), ("ʊ", "uh")):
            path = Path(folder) / (phone + ".wav")
            synth(f"pau {phone} pau".encode(), voice, bytes(path))
            with wave.open(str(path), "rb") as wav:
                assert wav.getframerate() == RATE and wav.getsampwidth() == 2 and wav.getnchannels() == 1
                vowels[symbol] = compress(wav.readframes(wav.getnframes()))
    (DIST / "vowel-audio-data.js").write_text(
        "/* Isolated American-English teaching sounds. Generated with Flite US SLT. */\n"
        + "window.VowelRecordings=Object.freeze(" + json.dumps(vowels, indent=1) + ");\n", encoding="utf-8")


def main():
    write_vowels()
    words = json.loads(subprocess.check_output([
        "node", "-e", "global.window={};require('./vocab-data.js');console.log(JSON.stringify(window.EnglishWords.map(x=>x.word)))"
    ], cwd=DIST))
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        catalog = dict(pool.map(encode, words))
    target = DIST / "word-audio-data.js"
    target.write_text("/* Generated by tools/build_word_audio.py using CMU Flite's US SLT voice. */\n"
                      + "window.WordRecordings=Object.freeze(" + json.dumps(catalog, indent=1) + ");\n", encoding="utf-8")
    print(f"{len(catalog)} words, {target.stat().st_size} bytes")


if __name__ == "__main__":
    main()
